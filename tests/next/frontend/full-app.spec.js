test('Display choices belongs to Settings and defaults to Compact without overriding a saved choice', async ({ page }) => {
  await signIn(page, 'owner');
  await expect(page.getByRole('button', { name: 'Display choices', exact: true })).toHaveCount(0);
  await expect(page.locator('body')).toHaveAttribute('data-spacing', 'compact');
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Display choices', exact: true }).click();
  await expect(page.getByLabel('Spacing', { exact: true })).toHaveValue('compact');
  await expect(page.getByLabel('Picture prominence', { exact: true })).toHaveCount(0);
  await page.getByLabel('Spacing', { exact: true }).selectOption('roomy');
  await page.getByRole('button', { name: 'Save display choices', exact: true }).click();
  await page.getByRole('link', { name: 'Home', exact: true }).click();
  await page.reload();
  await expect(page.locator('body')).toHaveAttribute('data-spacing', 'roomy');
  await expect(page.getByRole('button', { name: 'Display choices', exact: true })).toHaveCount(0);
});
async function signIn(page, actor = 'reader', editor = false) {
  await page.goto(editor ? '/editor.html' : '/#home');
  await page.getByLabel('Account', { exact: true }).fill(actor);
  await page.getByLabel('Password', { exact: true }).fill(actor + '-fictional-only');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: editor ? 'Settings' : 'Home', exact: true })).toBeVisible();
}

