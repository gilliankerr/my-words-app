test('a display conflict shows all choices and cannot overwrite an intervening revision', async ({ browser }) => {
  const a = await browser.newContext(), b = await browser.newContext(); const pa = await a.newPage(), pb = await b.newPage();
  await signIn(pa, 'alex', true); await signIn(pb, 'robin', true);
  for (const p of [pa, pb]) await p.getByRole('button', { name: 'Display choices', exact: true }).click();
  await pa.getByLabel('Text size', { exact: true }).selectOption('24'); await pa.getByLabel('Spacing', { exact: true }).selectOption('roomy');
  await pa.getByRole('button', { name: 'Save display choices', exact: true }).click();
  await expect(pa.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible();
  await pb.getByLabel('Text size', { exact: true }).selectOption('28'); await pb.getByLabel('Spacing', { exact: true }).selectOption('compact');
  await pb.getByRole('button', { name: 'Save display choices', exact: true }).click();
  await expect(pb.getByRole('heading', { name: 'Changes need review', exact: true })).toBeVisible();
  await expect(pb.getByRole('heading', { name: 'Text size', exact: true })).toHaveCount(3);
  await expect(pb.locator('.version').nth(2).getByText('28', { exact: true })).toBeVisible(); await expect(pb.locator('.version').nth(1).getByText('24', { exact: true })).toBeVisible();
  await pa.getByRole('button', { name: 'Display choices', exact: true }).click(); await pa.getByLabel('Text size', { exact: true }).selectOption('20');
  await pa.getByRole('button', { name: 'Save display choices', exact: true }).click();
  await expect(pa.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible();
  await pb.getByRole('button', { name: 'Use my choices', exact: true }).click();
  await expect(pb.getByRole('heading', { name: 'Changes need review', exact: true })).toBeVisible();
  await pb.getByRole('button', { name: 'Keep latest', exact: true }).click();
  await expect(pb.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible();
  await a.close(); await b.close();
});
