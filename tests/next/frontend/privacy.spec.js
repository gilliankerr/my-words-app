const { test, expect } = require('@playwright/test');
for (const width of [320, 820]) test(`privacy is readable before sign-in and offers the public support email at ${width}px`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 915 });
  await page.goto('/privacy.html');
  await expect(page.getByRole('heading', { name: 'Privacy and development', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'MIT licence', exact: true })).toHaveAttribute('href', '/licence.txt');
  await expect(page.getByText('Other open tabs may still show saved content until they check the session.', { exact: false })).toBeVisible();
  await expect(page.getByRole('link', { name: 'mywordssupport@gmail.com', exact: true })).toHaveAttribute('href', 'mailto:mywordssupport@gmail.com');
  await expect(page.locator('a[href^="mailto:"]')).toHaveCount(1);
  await expect(page.getByRole('link', { name: 'Contact support', exact: true })).toHaveCount(0);
  await expect(page.getByText(/contact button opens/i)).toHaveCount(0);
  await expect(page.getByText('mywordssupport@gmail.com', { exact: true })).toBeVisible();
  const contact = page.getByRole('link', { name: 'mywordssupport@gmail.com', exact: true });
  await contact.scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('contact-' + width + '.png'), fullPage: false });
  await expect(page.locator('form, input, textarea')).toHaveCount(0);
  await expect(page.locator('script[src="/js/repository.js"]')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath(`privacy-${width}.png`), fullPage: false });
});
test('privacy is linked from Settings and Help and remains readable offline', async ({ page, context }) => {
  await page.goto('/editor.html');
  await page.getByLabel('Account', { exact: true }).fill('owner'); await page.getByLabel('Password', { exact: true }).fill('owner-fictional-only');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Help', exact: true }).getByRole('link', { name: 'Privacy, development and licence', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Help using My Words', exact: true }).click();
  const privacy = page.getByRole('link', { name: 'Privacy, development and licence', exact: true }); await expect(privacy).toBeVisible();
  await page.evaluate(() => navigator.serviceWorker.ready);
  await context.setOffline(true); await privacy.click();
  await expect(page.getByRole('heading', { name: 'Privacy and development', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'mywordssupport@gmail.com', exact: true })).toHaveAttribute('href', 'mailto:mywordssupport@gmail.com');
  await expect(page.locator('a[href^="mailto:"]')).toHaveCount(1);
  await expect(page.getByRole('link', { name: 'Contact support', exact: true })).toHaveCount(0);
  await expect(page.getByText(/contact button opens/i)).toHaveCount(0);
  await page.getByRole('link', { name: 'MIT licence', exact: true }).click();
  await expect(page.locator('body')).toContainText('MIT License');
  await page.goto('/privacy.html');
  await page.getByRole('link', { name: 'CC BY-SA 4.0', exact: true }).click();
  await expect(page.locator('body')).toContainText('The Mulberry Symbol set');
  await expect(page.locator('body')).toContainText('Creative Commons Attribution-Share Alike');
  await context.setOffline(false);
});
